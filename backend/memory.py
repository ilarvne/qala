"""Explicitly opted-in preferences. No messages, precise locations or phone numbers.

Session IDs are unguessable bearer capabilities generated by the client. SQLite
contains their SHA-256 digests. Expiry is enforced on every operation.
"""
from __future__ import annotations

import hashlib
import json
import sqlite3
import time
from pathlib import Path

from .models import MemoryUpdateRequest, RecommendRequest
from .retrieval import ALIASES, FINE_TYPES, INTEREST_CATEGORIES


class StaleConsentGeneration(ValueError):
    """The caller's saved-preference capability version has been revoked."""


class PreferenceMemory:
    def __init__(self, path: Path):
        path.parent.mkdir(parents=True, exist_ok=True)
        self.path = path
        with self._connection() as conn:
            conn.execute("CREATE TABLE IF NOT EXISTS preferences (session_hash TEXT PRIMARY KEY, preferences TEXT NOT NULL, expires_at REAL NOT NULL)")
            conn.execute("CREATE TABLE IF NOT EXISTS consent_epochs (session_hash TEXT PRIMARY KEY, generation INTEGER NOT NULL, expires_at REAL NOT NULL)")

    def _connection(self):
        return sqlite3.connect(self.path, timeout=10)

    @staticmethod
    def _key(session: str):
        return hashlib.sha256(session.encode()).hexdigest()

    @staticmethod
    def _cleanup(conn):
        now = time.time()
        conn.execute("DELETE FROM preferences WHERE expires_at < ?", (now,))
        conn.execute("DELETE FROM consent_epochs WHERE expires_at < ?", (now,))

    def snapshot(self, session: str | None) -> tuple[dict | None, int]:
        """Atomically capture preferences and the request's consent generation."""
        with self._connection() as conn:
            conn.execute("BEGIN IMMEDIATE")
            self._cleanup(conn)
            key = self._key(session or "")
            row = conn.execute("SELECT preferences FROM preferences WHERE session_hash = ?", (key,)).fetchone()
            epoch = conn.execute("SELECT generation FROM consent_epochs WHERE session_hash = ?", (key,)).fetchone()
        return (json.loads(row[0]) if row else None, epoch[0] if epoch else 0)

    def get(self, session: str | None) -> dict | None:
        return self.snapshot(session)[0]

    def save(self, request: RecommendRequest, interests: list[str], expected_generation: int | None = None) -> dict | None:
        if not request.remember or not request.session_id:
            return self.get(request.session_id)
        preferences = {"interests": [key for key in interests if key in ALIASES][:15], "language": request.language, "duration_minutes": request.duration_minutes,
                       "accessible": request.accessible, "indoor": request.indoor,
                       "excluded_categories": [key for key in request.excluded_categories if key in set().union(*INTEREST_CATEGORIES.values()) | FINE_TYPES],
                       "max_walk_minutes": request.max_walk_minutes,
                       "coarse_location": {"lat": round(request.location.lat, 2), "lon": round(request.location.lon, 2)},
                       "retention_days": 30}
        with self._connection() as conn:
            conn.execute("BEGIN IMMEDIATE")
            self._cleanup(conn)
            key = self._key(request.session_id)
            epoch = conn.execute("SELECT generation FROM consent_epochs WHERE session_hash = ?", (key,)).fetchone()
            generation = epoch[0] if epoch else 0
            if (expected_generation is not None and generation != expected_generation) or (request.memory_generation is not None and generation != request.memory_generation):
                return None
            conn.execute("INSERT INTO preferences VALUES (?, ?, ?) ON CONFLICT(session_hash) DO UPDATE SET preferences=excluded.preferences, expires_at=excluded.expires_at", (key, json.dumps(preferences), time.time() + 30 * 86400))
        return preferences

    def update(self, session: str, request: MemoryUpdateRequest) -> dict:
        """An explicit preference edit invalidates older in-flight snapshots."""
        with self._connection() as conn:
            conn.execute("BEGIN IMMEDIATE")
            self._cleanup(conn)
            key = self._key(session)
            epoch = conn.execute("SELECT generation FROM consent_epochs WHERE session_hash = ?", (key,)).fetchone()
            generation = epoch[0] if epoch else 0
            if request.memory_generation is not None and request.memory_generation != generation:
                raise StaleConsentGeneration("Saved preferences changed. Refresh them before saving.")
            row = conn.execute("SELECT preferences FROM preferences WHERE session_hash = ?", (key,)).fetchone()
            preferences = json.loads(row[0]) if row else {}
            update = request.model_dump(exclude_unset=True, exclude={"consent", "memory_generation"})
            if "interests" in update:
                update["interests"] = list(dict.fromkeys(x for x in update["interests"] if x in ALIASES))
            if update.get("excluded_categories") is not None:
                update["excluded_categories"] = [x for x in update["excluded_categories"] if x in set().union(*INTEREST_CATEGORIES.values()) | FINE_TYPES]
            preferences.update(update)
            preferences["retention_days"] = 30
            conn.execute("INSERT INTO consent_epochs VALUES (?, 1, ?) ON CONFLICT(session_hash) DO UPDATE SET generation=generation+1, expires_at=excluded.expires_at", (key, time.time() + 30 * 86400))
            conn.execute("INSERT INTO preferences VALUES (?, ?, ?) ON CONFLICT(session_hash) DO UPDATE SET preferences=excluded.preferences, expires_at=excluded.expires_at", (key, json.dumps(preferences), time.time() + 30 * 86400))
        return preferences

    def delete(self, session: str):
        with self._connection() as conn:
            conn.execute("BEGIN IMMEDIATE")
            self._cleanup(conn)
            key = self._key(session)
            conn.execute("INSERT INTO consent_epochs VALUES (?, 1, ?) ON CONFLICT(session_hash) DO UPDATE SET generation=generation+1, expires_at=excluded.expires_at", (key, time.time() + 30 * 86400))
            conn.execute("DELETE FROM preferences WHERE session_hash = ?", (key,))
            return conn.execute("SELECT generation FROM consent_epochs WHERE session_hash = ?", (key,)).fetchone()[0]
